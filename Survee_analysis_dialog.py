import os

from qgis.PyQt import uic
from qgis.PyQt import QtWidgets, QtCore


FORM_CLASS, _ = uic.loadUiType(
    os.path.join(
        os.path.dirname(__file__),
        'Survee_analysis_dialog.ui'
    )
)


class SurveeAnalysisDialog(QtWidgets.QDialog, FORM_CLASS):

    def __init__(
        self,
        layer,
        total,
        lines,
        points,
        polygons,
        parent=None
    ):
        super(SurveeAnalysisDialog, self).__init__(parent)

        self.setupUi(self)

        self.layer = layer

        self.populate_layers()

        self.lblTotal.setText(
            f"Total de entidades: {total}"
        )

        self.lblLines.setText(
            f"Linhas: {lines}"
        )

        self.lblPoints.setText(
            f"Pontos: {points}"
        )

        self.lblPolygons.setText(
            f"Polígonos: {polygons}"
        )

        self.btnCancel.clicked.connect(self.reject)
        self.btnContinue.clicked.connect(self.continue_analysis)

    def populate_layers(self):

        layer_field = None

        for field in self.layer.fields():

            field_name = field.name().lower()

            if field_name in ["layer", "layername"]:
                layer_field = field.name()
                break

        if layer_field is None:
            return

        layers = set()

        for feature in self.layer.getFeatures():

            layer_name = feature[layer_field]

            if layer_name:
                layers.add(str(layer_name))

        for layer_name in sorted(layers):

            item = QtWidgets.QListWidgetItem(layer_name)

            item.setFlags(
                item.flags()
                | QtCore.Qt.ItemIsUserCheckable
            )

            item.setCheckState(
                QtCore.Qt.Checked
            )

            self.lstLayers.addItem(item)

    def get_selected_layers(self):

        selected_layers = []

        for i in range(self.lstLayers.count()):

            item = self.lstLayers.item(i)

            if item.checkState() == QtCore.Qt.Checked:
                selected_layers.append(item.text())

        return selected_layers

    def continue_analysis(self):

        self.selected_layers = self.get_selected_layers()

        if not self.selected_layers:
            QtWidgets.QMessageBox.warning(
                self,
                "Survee",
                "Selecione pelo menos uma layer."
            )
            return

        self.accept()