    def select_dxf(self):
        file_path, _ = QFileDialog.getOpenFileName(
            self,
            "Selecionar ficheiro DXF / DWG",
            "",
            "Ficheiros CAD (*.dxf *.dwg);;DXF files (*.dxf);;DWG files (*.dwg)"
        )

        if not file_path:
            return

        # Obter o CRS selecionado pelo utilizador
        chosen_crs = self.mCrsSelector.crs()

        # Remover o DXF anterior do projeto, caso esteja adicionado
        project = QgsProject.instance()

        if self.dxf_layer is not None:
            if project.mapLayer(self.dxf_layer.id()) is not None:
                project.removeMapLayer(self.dxf_layer.id())

        self.lblDxfPath.setText(file_path)

        # Carregar o ficheiro (o OGR do QGIS suporta DXF e alguns DWG)
        self.dxf_layer = QgsVectorLayer(
            file_path,
            "CAD - Origem",
            "ogr"
        )

        if not self.dxf_layer.isValid():
            QtWidgets.QMessageBox.warning(
                self,
                "Survee",
                "Não foi possível carregar o ficheiro CAD (.dxf / .dwg).\n\n"
                "Nota: Para alguns ficheiros .dwg, o QGIS pode necessitar "
                "de ferramentas externas de conversão (como o ODA File Converter)."
            )
            self.dxf_layer = None
            return

        if chosen_crs.isValid():
            self.dxf_layer.setCrs(chosen_crs)

        # Não adicionar o DXF original ao projeto.
        # Será utilizado apenas para análise e filtragem.

    def analyze_dxf(self):

        if self.dxf_layer is None:
            QtWidgets.QMessageBox.warning(
                self,
                "Survee",
                "Nenhum ficheiro DXF foi carregado."
            )
            return

        total = 0
        lines = 0
        points = 0
        polygons = 0

        for feature in self.dxf_layer.getFeatures():
            total += 1
            geometry = feature.geometry()

            if geometry.isEmpty():
                continue

            geometry_type = QgsWkbTypes.geometryType(
                geometry.wkbType()
            )

            if geometry_type == QgsWkbTypes.LineGeometry:
                lines += 1
            elif geometry_type == QgsWkbTypes.PointGeometry:
                points += 1
            elif geometry_type == QgsWkbTypes.PolygonGeometry:
                polygons += 1

        dialog = SurveeAnalysisDialog(
            self.dxf_layer,
            total,
            lines,
            points,
            polygons,
            self
        )

        result = dialog.exec()

        if result == QtWidgets.QDialog.Accepted:
            selected_layers = dialog.selected_layers
            line_layer = self.create_selected_layer(selected_layers)

            if line_layer is not None:
                self.create_polygons(line_layer)

    def create_selected_layer(self, selected_layers):

        source_layer = self.dxf_layer

        if source_layer is None or not source_layer.isValid():
            QtWidgets.QMessageBox.warning(
                self,
                "Survee",
                "Não existe uma camada DXF válida."
            )
            return None

        # Procurar o campo que identifica a layer do DXF
        layer_field = None

        for field in source_layer.fields():
            field_name = field.name().lower()

            if field_name in ["layer", "layername"]:
                layer_field = field.name()
                break

        if layer_field is None:
            QtWidgets.QMessageBox.warning(
                self,
                "Survee",
                "Não foi possível identificar as layers do DXF."
            )
            return None

        # Criar uma camada temporária de linhas
        selected_layer = QgsVectorLayer(
            "MultiLineString",
            "Survee - Linhas selecionadas",
            "memory"
        )

        # Preservar o CRS da camada original
        selected_layer.setCrs(source_layer.crs())

        # Copiar os campos da camada original
        provider = selected_layer.dataProvider()
        provider.addAttributes(source_layer.fields())
        selected_layer.updateFields()

        selected_features = []
        ignored_features = 0

        # Filtrar as entidades das layers escolhidas
        for feature in source_layer.getFeatures():

            layer_name = str(feature[layer_field])

            if layer_name not in selected_layers:
                continue

            geometry = feature.geometry()

            if geometry.isNull() or geometry.isEmpty():
                ignored_features += 1
                continue

            # Aceitar apenas geometrias lineares
            if QgsWkbTypes.geometryType(
                geometry.wkbType()
            ) != QgsWkbTypes.LineGeometry:
                ignored_features += 1
                continue

            # Converter linhas simples em multilinhas
            if not geometry.isMultipart():
                geometry.convertToMultiType()

            # Criar uma nova entidade com os atributos originais
            new_feature = QgsFeature(selected_layer.fields())
            new_feature.setAttributes(feature.attributes())
            new_feature.setGeometry(geometry)

            selected_features.append(new_feature)

        if not selected_features:
            QtWidgets.QMessageBox.warning(
                self,
                "Survee",
                "Não foram encontradas entidades lineares "
                "nas layers selecionadas."
            )
            return None

        # Inserir as entidades na camada temporária
        success, _ = provider.addFeatures(selected_features)

        if not success:
            QtWidgets.QMessageBox.warning(
                self,
                "Survee",
                "Ocorreu um erro ao criar a camada de linhas."
            )
            return None

        selected_layer.updateExtents()

        # Remover a camada anterior, caso ainda exista no projeto
        project = QgsProject.instance()

        if self.selected_line_layer_id is not None:
            old_layer = project.mapLayer(
                self.selected_line_layer_id
            )

            if old_layer is not None:
                project.removeMapLayer(
                    self.selected_line_layer_id
                )

            self.selected_line_layer_id = None
            self.selected_line_layer = None

        # Adicionar a nova camada ao projeto
        project.addMapLayer(selected_layer)

        self.selected_line_layer = selected_layer
        self.selected_line_layer_id = selected_layer.id()

        # Apresentar um resumo ao utilizador
        QtWidgets.QMessageBox.information(
            self,
            "Survee",
            f"Camada criada com sucesso.\n\n"
            f"Entidades lineares: {len(selected_features)}\n"
            f"Entidades ignoradas: {ignored_features}"
        )

        return selected_layer

    
    def create_polygons(self, line_layer):

        if line_layer is None or not line_layer.isValid():
            QtWidgets.QMessageBox.warning(
                self,
                "Survee",
                "Não existe uma camada de linhas válida."
            )
            return None

        try:
            # Converter as linhas em polígonos
            result = processing.run(
                "native:polygonize",
                {
                    "INPUT": line_layer,
                    "KEEP_FIELDS": False,
                    "OUTPUT": "memory:"
                }
            )

            polygon_layer = result["OUTPUT"]

            # Verificar o resultado
            if not isinstance(polygon_layer, QgsVectorLayer):
                polygon_layer = QgsVectorLayer(
                    polygon_layer,
                    "Survee - Polígonos",
                    "ogr"
                )

            if not polygon_layer.isValid():
                QtWidgets.QMessageBox.warning(
                    self,
                    "Survee",
                    "Não foi possível criar a camada de polígonos."
                )
                return None

            # Definir o nome da camada
            polygon_layer.setName("Survee - Polígonos")

            # Preservar o sistema de coordenadas
            polygon_layer.setCrs(line_layer.crs())

            # Definir um estilo visual para os polígonos
            symbol = QgsFillSymbol.createSimple({
                "color": "255,255,255,0",
                "outline_color": "255,70,0,255",
                "outline_width": "0.8",
                "outline_width_unit": "MM"
            })

            polygon_layer.renderer().setSymbol(symbol)
            polygon_layer.triggerRepaint()

            # Remover a camada anterior, se existir
            project = QgsProject.instance()

            if hasattr(self, "polygon_layer"):
                if self.polygon_layer is not None:
                    if project.mapLayer(self.polygon_layer.id()):
                        project.removeMapLayer(
                            self.polygon_layer.id()
                        )

            # Adicionar a nova camada ao projeto
            project.addMapLayer(polygon_layer)

            self.polygon_layer = polygon_layer

            # Centrar o mapa na área dos polígonos
            if polygon_layer.featureCount() > 0:
                extent = polygon_layer.extent()
                extent.scale(1.15)

                iface.mapCanvas().setExtent(extent)
                iface.mapCanvas().refresh()

            # Adicionar a imagem de satélite
            self.add_satellite_layer()

            # Contar os polígonos criados
            polygon_count = polygon_layer.featureCount()

            if polygon_count == 0:
                QtWidgets.QMessageBox.warning(
                    self,
                    "Survee",
                    "Não foram criados polígonos.\n\n"
                    "Verifica se as linhas formam limites fechados."
                )
                return None

            # --- FECHAR A JANELA DO PLUGIN ANTES DE PERGUNTAR ---
            # Isto liberta o QGIS e permite ver perfeitamente o mapa e a imagem de satélite
            self.close()

            # --- PERGUNTAR SE DESEJA AVANÇAR PARA KML ---
            # O utilizador fica com o mapa livre para verificar e decide se avança
            reply = QtWidgets.QMessageBox.question(
                self,
                "Survee",
                f"Polígonos criados com sucesso! (Total: {polygon_count})\n\n"
                "Pode agora verificar o mapa e confirmar se os limites estão corretos.\n"
                "Deseja prosseguir para a exportação em formato KML?",
                QtWidgets.QMessageBox.Yes | QtWidgets.QMessageBox.No,
                QtWidgets.QMessageBox.Yes
            )

            if reply == QtWidgets.QMessageBox.Yes:
                # Função onde vais tratar da exportação para KML
                self.export_to_kml(polygon_layer)

            return polygon_layer

        except Exception as error:
            QtWidgets.QMessageBox.critical(
                self,
                "Survee",
                f"Ocorreu um erro ao criar os polígonos:\n\n{error}"
            )
            return None
    
    def add_satellite_layer(self):
        project = QgsProject.instance()
        layer_name = "Survee - Imagem de satélite"

        # Verificar se a camada já existe
        for layer in project.mapLayers().values():
            if layer.name() == layer_name:
                return layer

        # URI estruturado especificamente para o fornecedor XYZ do QGIS
        # O parâmetro zmax e zmin garantem que os tiles aparecem em qualquer nível de zoom
        uri = (
            "type=xyz&url="
            "https://server.arcgisonline.com/ArcGIS/rest/services/"
            "World_Imagery/MapServer/tile/%7Bz%7D/%7By%7D/%7Bx%7D"
            "&zmax=19&zmin=0"
        )

        satellite_layer = QgsRasterLayer(
            uri,
            layer_name,
            "wms"
        )

        if not satellite_layer.isValid():
            # Tentar um URL alternativo (ex: OpenStreetMap ou Esri direto) se o primeiro falhar
            uri_alt = (
                "type=xyz&url="
                "https://mt1.google.com/vt/lyrs=s&x=%7Bx%7D&y=%7By%7D&z=%7Bz%7D"
                "&zmax=20&zmin=0"
            )
            satellite_layer = QgsRasterLayer(uri_alt, layer_name, "wms")

        if not satellite_layer.isValid():
            QtWidgets.QMessageBox.warning(
                self,
                "Survee",
                "Não foi possível carregar a imagem de satélite.\n\n"
                "Verifica a tua ligação à Internet."
            )
            return None

        # Adicionar a camada ao projeto (sem sinalizar logo no painel para controlarmos a posição)
        project.addMapLayer(satellite_layer, False)

        # Inserir no fundo da árvore de camadas (Layer Tree)
        root = project.layerTreeRoot()
        root.insertChildNode(len(root.children()), QgsLayerTreeLayer(satellite_layer))

        return satellite_layer

    def export_to_kml(self, polygon_layer):
        # 1. Pedir ao utilizador o local e nome para guardar o ficheiro KML
        file_path, _ = QFileDialog.getSaveFileName(
            self,
            "Guardar Ficheiro KML",
            "",
            "KML files (*.kml)"
        )

        if not file_path:
            return

        if not file_path.lower().endswith(".kml"):
            file_path += ".kml"

        try:
            # 2. Configuração moderna usando writeAsVectorFormatV3
            options = QgsVectorFileWriter.SaveVectorOptions()
            options.driverName = "KML"
            options.fileEncoding = "UTF-8"
            
            # Reprojetar para WGS84 (EPSG:4326), obrigatório para KML/Google Earth
            target_crs = QgsCoordinateReferenceSystem("EPSG:4326")
            options.ct = QgsCoordinateTransform(
                polygon_layer.crs(),
                target_crs,
                QgsProject.instance()
            )

            transform_context = QgsProject.instance().transformContext()

            # Chamada correta da API atualizada do QGIS
            error, error_string, _, _ = QgsVectorFileWriter.writeAsVectorFormatV3(
                polygon_layer,
                file_path,
                transform_context,
                options
            )

            if error == QgsVectorFileWriter.NoError:
                QtWidgets.QMessageBox.information(
                    self,
                    "Survee",
                    f"Ficheiro KML exportado com sucesso para:\n{file_path}"
                )
            else:
                QtWidgets.QMessageBox.warning(
                    self,
                    "Survee",
                    f"Ocorreu um erro ao exportar o ficheiro KML:\n{error_string}"
                )

        except Exception as error:
            QtWidgets.QMessageBox.critical(
                self,
                "Survee",
                f"Erro crítico na exportação:\n\n{error}"
            )